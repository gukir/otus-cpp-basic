// ============================================================
// 01_cout_basics.cpp
// Тема: как устроен cout и вывод в консоль
// ============================================================
//
// std::cout — это объект типа std::ostream, объявленный в <iostream>.
// Он связан со стандартным потоком вывода (обычно терминал).
// Оператор << называется "оператор вставки" (insertion operator) —
// он передаёт данные в поток.

// ============================================================

#include <iostream> // содержит std::cout, std::endl, std::cin и др.

int main() {
  // --- 1. Простейший вывод строкового литерала ---
  std::cout << "Привет, мир!\n";

  // --- 2. Цепочка вывода нескольких значений ---
  std::cout << "2 + 2 = " << 2 + 2 << "\n";

  // --- 3. std::endl vs "\n" ---
  // std::endl выводит '\n' И сбрасывает внутренний буфер потока (flush).
  // "\n" только добавляет символ новой строки — быстрее.
  std::cout << "Строка через std::endl" << std::endl;
  std::cout << "Строка через \\n" << "\n";

  // --- 4. Пустая строка и отступы ---
  std::cout << "\n"; // пустая строка
  std::cout << "  -> Отступ два пробела\n";
  std::cout << "\t-> Отступ табуляцией\n";

  // --- 5. Escape-последовательности ---
  std::cout << "Кавычки: \"цитата\"\n";
  std::cout << "Обратный слеш: \\\n";
}
