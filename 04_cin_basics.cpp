// ============================================================
// 04_cin_basics.cpp
// Тема: std::cin, ввод разных типов, обработка ошибок ввода
// ============================================================

#include <iostream>
#include <string>

int main() {
  // ========================================================
  // КАК РАБОТАЕТ std::cin
  // ========================================================
  //
  // std::cin — объект типа std::istream, связан со стандартным вводом.
  // Оператор >> называется "оператор извлечения" (extraction operator).
  //
  // По умолчанию >> пропускает пробелы/табуляции/переводы строк,
  // затем читает символы до следующего пробельного символа или
  // до конца буфера, подходящего для типа переменной.
  // ========================================================

  // --------------------------------------------------------
  // 1. Ввод строки (одно слово)
  // --------------------------------------------------------
  std::string firstName;
  std::cout << "Введите ваше имя: ";
  std::cin >> firstName; // читает до первого пробела
  std::cout << "Привет, " << firstName << "!\n\n";

  // --------------------------------------------------------
  // 2. Ввод числа (int)
  // --------------------------------------------------------
  int age;
  std::cout << "Введите ваш возраст: ";
  std::cin >> age;
  std::cout << "Вам " << age << " лет.\n\n";

  // --------------------------------------------------------
  // 3. Ввод нескольких значений в одной строке
  // --------------------------------------------------------
  // Пользователь может вводить через пробел или нажимая Enter —
  // для cin >> это одинаково.
  int day, month, year;
  std::cout << "Введите дату рождения (день месяц год): ";
  std::cin >> day >> month >> year;
  std::cout << "Дата: " << day << "/" << month << "/" << year << "\n\n";

  // --------------------------------------------------------
  // 5. Что происходит при вводе строки вместо числа
  // --------------------------------------------------------
  // Если пользователь введёт "abc" в int-переменную:
  //   - операция извлечения завершается неудачей
  //   - поток переходит в состояние ошибки (failbit)
  //   - переменная зануляется
  //   - последующие операции чтения игнорируются, пока ошибка не будет сброшена

  std::cout << "=== Демонстрация ошибки ввода ===\n";
  int salary;
  std::cout << "Введите зарплату (число). Попробуйте ввести текст: ";
  std::cin >> salary;

  int salary2;
  std::cout << "Введите зарплату (число) повторно: ";
  std::cin >> salary2;
}
