#include <iostream>

int main() {
  std::cout << "=== Калькулятор суммы ===\n\n";

  int number1{0};
  int number2{0};
  std::cout << "Ведите подряд два числа: ";
  std::cin >> number1 >> number2;

  std::cout << "Сумма: " << number1 + number2;
}
