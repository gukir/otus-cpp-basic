// ============================================================
// 02_variables_and_int.cpp
// Тема: переменные, именование, инициализация, тип int и его семья
// ============================================================

#include <climits> // INT_MAX, INT_MIN, UINT_MAX, ...
#include <cstdint> // int8_t, int16_t, int32_t, int64_t, ...
#include <iostream>

// ---- Правила именования -----------------------------------
// Хорошие имена: age, userName, totalScore, maxRetries
// Плохие имена:  a, x1, aaa, TEMP2
//
// Соглашения (нет единого стандарта, но популярные):
//   camelCase  — userAge       (Qt, Android)
//   snake_case — user_age      (стандартная библиотека C++)
//
// Запрещено: начинаться с цифры, содержать пробел или '-',
//            совпадать с ключевыми словами (int, for, while...).
// -----------------------------------------------------------

int main() {
  // ========================================================
  // СПОСОБЫ ИНИЦИАЛИЗАЦИИ
  // ========================================================

  // 1. C-style (копирующая инициализация)
  int a = 10;

  // 2. Прямая инициализация (direct initialization)
  int b(20);

  // 3. Uniform / brace initialization — рекомендуется в C++11 и позже.
  //    Её преимущество: запрещает сужающие преобразования.
  int c{30};

  // 4. Объявление без инициализации
  int garbage; // содержит «мусор» — случайное значение из памяти
  std::cout << "garbage = " << garbage
            << "\n\n"; // неопределённое поведение (Undefined Behavior)

  // Всегда ли нужна инициализация?
  // - Глобальные и static переменные инициализируются 0 автоматически.
  // - Локальные (стек) — НЕ инициализируются. Всегда давайте им значение.
  int safeZero{0}; // явная инициализация нулём

  std::cout << "a=" << a << "  b=" << b << "  c=" << c
            << "  safeZero=" << safeZero << "\n\n";

  // ========================================================
  // СЕМЕЙСТВО ЦЕЛЫХ ТИПОВ
  // ========================================================
  // https://en.cppreference.com/cpp/language/types
  // Стандарт гарантирует только минимальные размеры и диапазоны:
  //   char        >= 1 байт  |  -128 .. 127  (signed)  /  0 .. 255  (unsigned)
  //   short       >= 2 байта |  -32 768 .. 32 767       /  0 .. 65 535
  //   int         >= 2 байта |  -2 147 483 648 .. 2 147 483 647  (на практике 4
  //   байта, x86/x64) long        >= 4 байта |  на Windows x64: как int;  на
  //   Linux x64: как long long long long   >= 8 байт  |  -9 223 372 036 854 775
  //   808 .. 9 223 372 036 854 775 807

  std::cout << "=== Размеры типов (sizeof) ===\n";
  std::cout << "char:       " << sizeof(char) << " байт\n";
  std::cout << "short:      " << sizeof(short) << " байт\n";
  std::cout << "int:        " << sizeof(garbage) << " байт\n";
  std::cout << "long:       " << sizeof(long)
            << " байт  <- различается на платформах!\n";
  std::cout << "long long:  " << sizeof(long long) << " байт\n";
  std::cout << "int32_t:    " << sizeof(int32_t) << " байт  (всегда 4)\n";
  std::cout << "int64_t:    " << sizeof(int64_t) << " байт  (всегда 8)\n";
  std::cout << "\n";

  // ========================================================
  // ДИАПАЗОНЫ ЗНАЧЕНИЙ
  // ========================================================
  std::cout << "=== Диапазоны int ===\n";
  std::cout << "INT_MIN  = " << INT_MIN << "\n";
  std::cout << "INT_MAX  = " << INT_MAX << "\n";
  std::cout << "UINT_MAX = " << UINT_MAX << "\n";
  std::cout << "\n";

  // ========================================================
  // ПЕРЕПОЛНЕНИЕ (Overflow)
  // ========================================================
  // Для signed int переполнение — Undefined Behavior!
  // Для unsigned — поведение чётко определено: «обёртывание» (wrap-around).

  unsigned int umax = UINT_MAX;
  std::cout << "=== Переполнение ===\n";
  std::cout << "UINT_MAX + 1 = " << (umax + 1u)
            << "  (unsigned wrap-around: 0)\n";

  // Пример с signed (технически UB, но почти везде так):
  int imax = INT_MAX;
  std::cout << "INT_MAX + 1  = " << (imax + 1)
            << "  (signed: UB, обычно -2147483648)\n\n";

  // ========================================================
  // АРИФМЕТИЧЕСКИЕ ОПЕРАЦИИ
  // ========================================================
  int x = 17, y = 5;
  std::cout << "=== Арифметика (x=17, y=5) ===\n";
  std::cout << "x + y  = " << (x + y) << "\n";
  std::cout << "x - y  = " << (x - y) << "\n";
  std::cout << "x * y  = " << (x * y) << "\n";
  std::cout << "x / y  = " << (x / y) << "  (целочисленное деление!)\n";
  std::cout << "x % y  = " << (x % y) << "  (остаток от деления)\n\n";

  // ========================================================
  // ОПЕРАЦИИ ПРИСВАИВАНИЯ И ИНКРЕМЕНТ
  // ========================================================
  int score = 100;
  score += 10; // score = score + 10
  score -= 5;  // score = score - 5
  score *= 2;  // score = score * 2
  score /= 3;  // score = score / 3
  std::cout << "score после += 10, -= 5, *= 2, /= 3: " << score << "\n";

  int counter = 0;
  counter++; // постфиксный инкремент
  ++counter; // префиксный инкремент (чуть эффективнее для объектов)
  std::cout << "counter после двух инкрементов: " << counter << "\n\n";
}
